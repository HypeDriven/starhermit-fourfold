// Writes the play scripts whose moves come from the rules: Journey stage 1
// against Casual AI, won by number keys (our side plays the Sharp search on
// a stream of its own, so the rival's seeded stream runs exactly as in the
// game), to the results sheet and Next. The rival answers through the same
// js/ai.js with the stage's seed, so the script's waits match the game.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const R = require('../js/rules.js'), C = require('../js/content.js'), AI = require('../js/ai.js'), RNG = require('../js/rng.js');

function plan(stageId) {
  const cfg = JSON.parse(JSON.stringify(C.JOURNEY.find((j) => j.id === stageId)));
  const s = R.createGame(cfg);
  const rival = RNG.derive(cfg.seed, RNG.STREAM_AI), mine = RNG.create(4242);
  const moves = [];
  while (!s.terminal) {
    if (s.current === 1) { const c = AI.chooseMove(s, 3, mine); moves.push(c); R.applyCommand(s, { type: 'drop', col: c }); }
    else R.applyCommand(s, { type: 'drop', col: AI.chooseMove(s, cfg.ai, rival) });
  }
  return { cfg, moves, won: s.terminal.winner === 1, score: s.score.total };
}

const j = plan('j01');
if (!j.won) throw new Error('the plan does not win j01');
const lines = [
  '# Generated by tools/gen-plays.mjs: Journey stage 1 against Casual AI, won by',
  '# number keys, to the results sheet, its stars and score, and Next.',
  'until 600 Make four in a row', 'frames 30', 'click =Journey', 'until 120 Stars come from winning', 'frames 10',
  `click ${'1. ' + j.cfg.name}`, `until 120 ${j.cfg.intro.slice(0, 30)}`, 'frames 30',
];
j.moves.forEach((c, i) => {
  lines.push(`key Digit${c + 1} 1`, 'frames 5');
  if (i < j.moves.length - 1) lines.push('until 600 =Your turn', 'frames 5');
});
lines.push('until 300 =You made four', 'frames 120', 'save journey-results', `expect ${j.score}`, 'click Next:', 'until 120 =Your turn', 'frames 10', 'expect Connect 4');
writeFileSync(new URL('../tests/native/journey.play', import.meta.url), lines.join('\n') + '\n');
console.log(`journey.play: ${j.moves.length} drops, score ${j.score}`);
